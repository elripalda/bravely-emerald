#!/usr/bin/env python3
"""Renders the two serif words of the HD-2D title (BRAVELY and HD-2D) once into small 8-bit alpha masks and writes them as
run-length encoded C arrays (src/platform/deck/deck_title_font.h). The font is only read here, not at run time.

usage: gen_title_font.py <font.ttf> <out.h> [preview.png]
Font used for the committed header: Cinzel Regular (SIL OFL 1.1, Copyright 2020 The Cinzel Project Authors, https://github.com/google/fonts/tree/main/ofl/cinzel), licence in docs/licenses/Cinzel-OFL.txt.
"""
import sys
from PIL import Image, ImageDraw, ImageFont


def render(font_path, text, size, tracking, pad):
    f = ImageFont.truetype(font_path, size)
    widths = [f.getlength(c) for c in text]
    w = int(sum(widths) + tracking * (len(text) - 1)) + 2 * pad
    asc, desc = f.getmetrics()
    h = asc + desc + 2 * pad
    im = Image.new("L", (w, h), 0)
    d = ImageDraw.Draw(im)
    x = float(pad)
    for c, cw in zip(text, widths):
        d.text((x, pad), c, font=f, fill=255)
        x += cw + tracking
    bbox = im.getbbox()
    return im.crop((max(bbox[0] - 2, 0), max(bbox[1] - 2, 0), min(bbox[2] + 2, w), min(bbox[3] + 2, h)))


def rle(data):
    out = []
    i = 0
    while i < len(data):
        v = data[i]
        n = 1
        while i + n < len(data) and data[i + n] == v and n < 255:
            n += 1
        out += [v, n]
        i += n
    return out


def emit(name, im, f):
    data = list(im.tobytes())
    r = rle(data)
    f.write("static const unsigned char %s[] = {\n" % name)
    for i in range(0, len(r), 24):
        f.write("    " + ",".join(str(v) for v in r[i:i + 24]) + ",\n")
    f.write("};\n#define %s_W %d\n#define %s_H %d\n\n" % (name.upper(), im.width, name.upper(), im.height))
    return len(r)


def main():
    font, out = sys.argv[1], sys.argv[2]
    bravely = render(font, "BRAVELY", 150, 16, 8)
    hd = render(font, "HD-2D", 90, 10, 6)
    with open(out, "w") as f:
        f.write("// Generated by tools/deck/gen_title_font.py from Cinzel (SIL Open Font License 1.1, see docs/licenses/Cinzel-OFL.txt). Do not edit.\n")
        f.write("// 8-bit alpha masks, run-length encoded as (value, count) byte pairs.\n\n")
        n1 = emit("kBravelyRle", bravely, f)
        n2 = emit("kHd2dRle", hd, f)
    print("BRAVELY %dx%d rle %d bytes, HD-2D %dx%d rle %d bytes" % (bravely.width, bravely.height, n1, hd.width, hd.height, n2))
    if len(sys.argv) > 3:
        pv = Image.new("L", (max(bravely.width, hd.width), bravely.height + hd.height + 10), 128)
        pv.paste(bravely, (0, 0))
        pv.paste(hd, (0, bravely.height + 10))
        pv.save(sys.argv[3])


main()
